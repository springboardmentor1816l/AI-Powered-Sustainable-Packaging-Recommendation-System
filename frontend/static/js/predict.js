document.addEventListener('DOMContentLoaded', function() {
    // Results Page Logic - Check this FIRST before form logic
    if (window.location.pathname === '/results') {
        console.log('Results page detected');
        const resultData = sessionStorage.getItem('predictionResult');
        console.log('Retrieved data:', resultData);
        
        if (resultData) {
            try {
                const result = JSON.parse(resultData);
                console.log('Parsed result:', result);
                
                // Update UI with better error handling
                const costElement = document.getElementById('predictedCost');
                const co2Element = document.getElementById('predictedCO2');
                const materialElement = document.getElementById('recommendedMaterial');
                
                if (costElement && result.predicted_cost !== undefined) {
                    costElement.textContent = `₹${result.predicted_cost.toFixed(2)}`;
                } else {
                    console.error('Cost element not found or cost data missing');
                }
                
                if (co2Element && result.predicted_co2_impact !== undefined) {
                    co2Element.textContent = `${result.predicted_co2_impact.toFixed(2)} kg`;
                } else {
                    console.error('CO2 element not found or CO2 data missing');
                }
                
                // Determine recommended material based on input
                if (materialElement) {
                    const inputMaterial = result.material_type || 'Unknown';
                    materialElement.textContent = `Eco-Friendly ${inputMaterial.charAt(0).toUpperCase() + inputMaterial.slice(1)}`;
                }
                
            } catch (error) {
                console.error('Error parsing result data:', error);
                window.location.href = '/input';
            }
        } else {
            console.log('No result data found, redirecting to input');
            window.location.href = '/input';
        }

        // PDF Download Handler - Added inside results page logic
        const downloadBtn = document.getElementById('downloadPDF');
        if (downloadBtn) {
            downloadBtn.addEventListener('click', function() {
                const resultData = sessionStorage.getItem('predictionResult');
                if (!resultData) {
                    alert('No prediction data available');
                    return;
                }

                const result = JSON.parse(resultData);
                
                // Check if jsPDF is loaded
                if (typeof window.jspdf === 'undefined') {
                    alert('PDF library not loaded. Please refresh the page.');
                    return;
                }
                
                const { jsPDF } = window.jspdf;
                const doc = new jsPDF();

                // Add header
                doc.setFillColor(46, 125, 50);
                doc.rect(0, 0, 210, 40, 'F');
                doc.setTextColor(255, 255, 255);
                doc.setFontSize(24);
                doc.text('EcoPackAI', 105, 20, { align: 'center' });
                doc.setFontSize(12);
                doc.text('Sustainable Packaging Recommendation Report', 105, 30, { align: 'center' });

                // Reset text color
                doc.setTextColor(0, 0, 0);
                doc.setFontSize(10);
                doc.text(`Generated: ${new Date().toLocaleString()}`, 14, 50);

                // Add results section
                doc.setFontSize(16);
                doc.setTextColor(46, 125, 50);
                doc.text('Prediction Results', 14, 70);

                doc.setFontSize(12);
                doc.setTextColor(0, 0, 0);
                doc.text(`Recommended Material: Eco-Friendly ${result.material_type || 'Material'}`, 14, 85);
                doc.text(`Predicted Cost: Rs. ${result.predicted_cost.toFixed(2)}`, 14, 95);
                doc.text(`CO2 Emission: ${result.predicted_co2_impact.toFixed(2)} kg`, 14, 105);

                // Add footer
                doc.setFontSize(8);
                doc.setTextColor(128, 128, 128);
                doc.text('This report is generated by EcoPackAI - AI-Powered Sustainable Packaging Solution', 105, 280, { align: 'center' });

                // Save the PDF
                doc.save('EcoPackAI-Prediction-Report.pdf');
            });
        }
        
        return; // Exit early for results page
    }

    // Input Form Logic - Only runs on input page
    const form = document.getElementById('predictionForm');
    if (!form) {
        console.log('No form found on this page');
        return;
    }

    const predictBtn = document.getElementById('predictBtn');
    const spinner = predictBtn ? predictBtn.querySelector('.spinner-border') : null;
    const errorAlert = document.getElementById('errorAlert');

    form.addEventListener('submit', async function(e) {
        e.preventDefault();
        console.log('Form submitted');
        
        // Reset state
        if (errorAlert) {
            errorAlert.classList.add('d-none');
            errorAlert.textContent = '';
        }
        if (predictBtn) predictBtn.disabled = true;
        if (spinner) spinner.classList.remove('d-none');

        // Gather data
        const formData = {
            product_weight_g: parseFloat(document.getElementById('productWeight').value),
            product_category: document.getElementById('productCategory').value,
            fragility_score: parseFloat(document.getElementById('fragilityScore').value),
            material_type: document.getElementById('materialType').value,
            material_recyclability_score: parseFloat(document.getElementById('recyclabilityScore').value),
            transport_distance_km: parseFloat(document.getElementById('transportDistance').value)
        };

        console.log('Form data:', formData);

        // Basic Validation
        if (!formData.product_category || !formData.material_type) {
            showError("Please select all required fields.");
            resetButton();
            return;
        }

        try {
            // API Call
            console.log('Calling API...');
            const response = await fetch('/predict', {
                method: 'POST',
                headers: {
                    'Content-Type': 'application/json',
                    'X-API-Key': 'default-dev-key'
                },
                body: JSON.stringify(formData)
            });

            console.log('Response status:', response.status);

            if (!response.ok) {
                const errorData = await response.json();
                throw new Error(errorData.error || 'Prediction failed');
            }

            const result = await response.json();
            console.log('API result:', result);
            
            // Store form data along with results
            result.material_type = formData.material_type;
            
            // Store results in sessionStorage to display on results page
            sessionStorage.setItem('predictionResult', JSON.stringify(result));
            console.log('Stored in sessionStorage');
            
            // Redirect to results page
            window.location.href = '/results';

        } catch (error) {
            console.error('Error:', error);
            showError(error.message);
            resetButton();
        }
    });

    function showError(message) {
        if (errorAlert) {
            errorAlert.textContent = message;
            errorAlert.classList.remove('d-none');
        }
    }

    function resetButton() {
        if (predictBtn) predictBtn.disabled = false;
        if (spinner) spinner.classList.add('d-none');
    }
});
